# BusGuard — one-time database setup
#
# Creates a dedicated `busguard` role and database on your EXISTING PostgreSQL
# server (the one running as a Windows service on port 5432). Your original
# `postgres` superuser, other databases, and your pg_hba.conf are left alone.
#
# Run from a PowerShell window:
#   powershell -ExecutionPolicy Bypass -File .\scripts\setup-db.ps1
#
# It will ask for your `postgres` password, then write .env for you.

$ErrorActionPreference = 'Stop'

$psql = 'C:\Program Files\PostgreSQL\17\bin\psql.exe'
if (-not (Test-Path $psql)) {
    Write-Host "psql not found at $psql" -ForegroundColor Red
    Write-Host "Edit the `$psql path at the top of this script to match your install." -ForegroundColor Yellow
    exit 1
}

if (-not (Test-Path '..\node_modules\.bin\prisma.cmd')) {
    Write-Host "Run 'npm install' first." -ForegroundColor Red
    exit 1
}

$secure = Read-Host -Prompt 'Password for PostgreSQL superuser "postgres"' -AsSecureString
$bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
$adminPassword = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr)
[Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr)

if ([string]::IsNullOrWhiteSpace($adminPassword)) {
    Write-Host "Password required." -ForegroundColor Red
    exit 1
}

$env:PGPASSWORD = $adminPassword

Write-Host "`n[1/3] Testing connection as superuser..." -ForegroundColor Cyan
& $psql -U postgres -h 127.0.0.1 -p 5432 -d postgres -tAc "SELECT 1;" | Out-Null
if ($LASTEXITCODE -ne 0) {
    Write-Host "`nCould not authenticate as 'postgres'. Check the password." -ForegroundColor Red
    Remove-Item Env:\PGPASSWORD
    exit 1
}
Write-Host "  ok" -ForegroundColor Green

# Generate a random password for the busguard role
$bytes = New-Object byte[] 24
[Security.Cryptography.RandomNumberGenerator]::Fill($bytes)
$appPassword = [Convert]::ToBase64String($bytes).Replace('+','a').Replace('/','b').Replace('=','')

Write-Host "`n[2/3] Creating role 'busguard' and database 'busguard'..." -ForegroundColor Cyan

$sql = @"
DO `$`$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'busguard') THEN
    CREATE ROLE busguard LOGIN PASSWORD '$appPassword';
  ELSE
    ALTER ROLE busguard LOGIN PASSWORD '$appPassword';
  END IF;
END
`$`$;
"@
$sql | & $psql -U postgres -h 127.0.0.1 -p 5432 -d postgres -v ON_ERROR_STOP=1 | Out-Null

$dbExists = & $psql -U postgres -h 127.0.0.1 -p 5432 -d postgres -tAc "SELECT 1 FROM pg_database WHERE datname='busguard';"
if ($dbExists.Trim() -ne '1') {
    & $psql -U postgres -h 127.0.0.1 -p 5432 -d postgres -c "CREATE DATABASE busguard OWNER busguard;" | Out-Null
    Write-Host "  database created" -ForegroundColor Green
} else {
    Write-Host "  database already existed, left as is" -ForegroundColor Yellow
}

# Prisma 7 needs CREATEDB for migrations
& $psql -U postgres -h 127.0.0.1 -p 5432 -d postgres -c "ALTER ROLE busguard CREATEDB;" | Out-Null
Write-Host "  role ready" -ForegroundColor Green

Remove-Item Env:\PGPASSWORD

Write-Host "`n[3/3] Writing .env..." -ForegroundColor Cyan

$envPath = Join-Path $PSScriptRoot '..\.env'
$escaped = $appPassword.Replace('\','\\').Replace('"','\"')
$envContent = @"
# BusGuard — local development
# Generated by scripts/setup-db.ps1
DATABASE_URL="postgresql://busguard:$escaped@127.0.0.1:5432/busguard?schema=public"

# 32+ byte random string. Generate one with:
#   node -e "console.log(require('crypto').randomBytes(32).toString('base64'))"
AUTH_SECRET="replace_me_before_running_migrations"

# Where the app runs, used to build absolute callback URLs
NEXT_PUBLIC_APP_URL="http://localhost:3000"

# OSRM public demo server for road-accurate ETA. No API key required.
# Self-host for production: https://github.com/Project-OSRM/osrm-backend
OSRM_URL="https://router.project-osrm.org"
"@
Set-Content -Path $envPath -Value $envContent -Encoding utf8
Write-Host "  .env written" -ForegroundColor Green

Write-Host "`nDone. Next steps:" -ForegroundColor Cyan
Write-Host "  1. Generate AUTH_SECRET and paste it into .env" -ForegroundColor White
Write-Host "  2. npx prisma migrate dev --name init" -ForegroundColor White
Write-Host "  3. npm run seed" -ForegroundColor White
Write-Host ""
